#!/usr/bin/env python3
"""Build a cyclic 280-pixel compass ribbon from the shared Beautiful Boot font."""
from pathlib import Path
import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[2] / 'dev/tools'))
from fonts import glyph, asm_bytes

rows = [bytearray(40) for _ in range(8)]
for bearing, label in enumerate(('N', 'NE', 'E', 'SE', 'S', 'SW', 'W', 'NW')):
    centre = bearing * 35
    for i, letter in enumerate(label):
        for y, bits in enumerate(glyph(letter)[:7]):
            for bit in range(7):
                if bits & (1 << bit):
                    x = (centre - len(label)*7//2 + i*7 + bit) % 280
                    rows[y][x//7] |= 1 << (x%7)
for tick in range(16):
    x = tick*35//2
    rows[7][x//7] |= 1 << (x%7)
lines = ['; Generated by tools/genhud.py: 2 azimuth units per ribbon pixel.',
         '.segment "TEXT"', 'hud_strip0:', asm_bytes(rows[0]), '.segment "LOWCODE"']
for y in range(1, 8):
    lines += [f'hud_strip{y}:', asm_bytes(rows[y])]
lines.append('.segment "GCODE"')
for part in ('lo', 'hi'):
    lines += [f'hud_strip_{part}:', '        .byte ' + ', '.join(f'{"<" if part == "lo" else ">"}hud_strip{y}' for y in range(8))]
Path(sys.argv[1]).write_text('\n'.join(lines)+'\n')
