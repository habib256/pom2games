#!/usr/bin/env python3
"""gentables.py: lookup tables of src/wild.s (ca65 has no floating point).

sin_lo: low byte of rounded sin(i * 90 / 140) * 256, i = 0..140.
SIN_UNIT_START: first sample equal to 256 (high byte derived by comparison).
col_be/col_bo: HGR byte of the even / odd pixel of screen column 0..139.
col_me/col_mo: and-mask that clears that pixel.
Second output: rowtab.inc, the screen row of each threshold increment.
"""
import math, sys

sinq = [round(256 * math.sin(i * math.pi / 2 / 140)) for i in range(141)]
rows = ['; generated by tools/gentables.py',
        f'SIN_UNIT_START = {sinq.index(256)}']


def table(name, values):
    rows.append(f'{name}:')
    for k in range(0, len(values), 16):
        rows.append('        .byte   ' + ', '.join(f'${v:02X}' for v in values[k:k + 16]))


table('sin_lo', [v & 255 for v in sinq])
table('col_be', [(2 * c) // 7 for c in range(140)])
table('col_bo', [(2 * c + 1) // 7 for c in range(140)])
table('col_me', [0xFF ^ (1 << ((2 * c) % 7)) for c in range(140)])
table('col_mo', [0xFF ^ (1 << ((2 * c + 1) % 7)) for c in range(140)])
open(sys.argv[1], 'w').write('\n'.join(rows) + '\n')

# rowtab.inc: screen row of tinc, 95 - ((3 * tinc) >> 4), or $FF below row
# 159 (same rule as tools/view_ref.py), in four pages indexed by |tinc| bits:
# row_p0[q] tinc = q, row_p1[q] tinc = 256 + q, row_n0[q] tinc = -q,
# row_n1[q] tinc = -(256 + q).
def row(tinc):
    off = (3 * tinc) >> 4
    return 95 - off if off >= -64 else 0xFF


rows = ['; generated by tools/gentables.py']
for name, f in (('row_p0', lambda q: q), ('row_p1', lambda q: 256 + q),
                ('row_n0', lambda q: -q), ('row_n1', lambda q: -256 - q)):
    vals = [row(f(q)) for q in range(256)]
    if name == 'row_n1':
        # The renderer rejects q >= 86 before reading this last table.
        # Its 170-byte $FF suffix otherwise occupies scarce resident RAM.
        vals = vals[:86]
    rows.append(f'{name}:')
    for k in range(0, len(vals), 16):
        rows.append('        .byte   ' + ', '.join(f'${v:02X}' for v in vals[k:k + 16]))
open(sys.argv[2], 'w').write('\n'.join(rows) + '\n')
