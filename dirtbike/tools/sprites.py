#!/usr/bin/env python3
"""Write src/sprites.inc: the pre-shifted wheel and head sprites.

    python3 tools/sprites.py src/sprites.inc

Wheel: 13x13, a two-pixel tyre (white on HGR, not a colour fringe) and two
spokes crossing at the hub. The spokes repeat every quarter turn, so
WHEEL_FRAMES frames cover 90 degrees. Each frame exists at the 7 pixel
shifts of an HGR byte: (frame * 7 + shift) * 13 rows * 3 bytes, bit 0 =
leftmost pixel. Head: 5x5 disc, 7 shifts * 5 rows * 2 bytes.
"""
import math
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / 'dev/tools'))
import apple2img  # noqa: E402

WHEEL = 13
WHEEL_FRAMES = 4
HEAD = 5


def wheel(frame):
    c = WHEEL // 2
    px = set()
    for y in range(WHEEL):
        for x in range(WHEEL):
            d = math.hypot(x - c, y - c)
            if 4.9 <= d <= 6.5:
                px.add((x, y))
    a0 = math.pi / 2 * frame / WHEEL_FRAMES
    for k in range(4):
        a = a0 + k * math.pi / 2
        for t in range(1, 9):
            r = t * 0.55
            px.add((round(c + r * math.cos(a)), round(c + r * math.sin(a))))
    px.add((c, c))
    return px, WHEEL


def head():
    c = HEAD // 2
    return {(x, y) for y in range(HEAD) for x in range(HEAD)
            if math.hypot(x - c, y - c) <= 2.3}, HEAD


def shifted(pixels, size, nbytes):
    """The 7 shifts of an HGR byte, one after the other: rows of nbytes."""
    rows = [[(x, y) in pixels for x in range(size)] for y in range(size)]
    return [r for ph in apple2img.preshift7(rows, size, nbytes) for r in ph]


def emit(name, rows):
    out = [f'{name}:']
    for r in rows:
        out.append('        .byte ' + ', '.join(f'${v:02X}' for v in r))
    return out


def main():
    out = ['; sprites.inc -- generated by tools/sprites.py. Do not edit.',
           f'WHEEL_H = {WHEEL}', f'WHEEL_FRAMES = {WHEEL_FRAMES}',
           f'WHEEL_BYTES = {WHEEL * 3}', f'HEAD_H = {HEAD}', f'HEAD_BYTES = {HEAD * 2}',
           '.segment "RODATA"']
    rows = []
    for f in range(WHEEL_FRAMES):
        px, n = wheel(f)
        rows += shifted(px, n, 3)
    out += emit('wheel_spr', rows)
    px, n = head()
    out += emit('head_spr', shifted(px, n, 2))
    out.append('; (frame * 7 + shift) -> sprite address')
    addrs = [f'wheel_spr + {i * WHEEL * 3}' for i in range(WHEEL_FRAMES * 7)]
    out.append('wheel_lo: .byte ' + ', '.join(f'<({a})' for a in addrs))
    out.append('wheel_hi: .byte ' + ', '.join(f'>({a})' for a in addrs))
    addrs = [f'head_spr + {i * HEAD * 2}' for i in range(7)]
    out.append('head_lo:  .byte ' + ', '.join(f'<({a})' for a in addrs))
    out.append('head_hi:  .byte ' + ', '.join(f'>({a})' for a in addrs))
    out.append('.segment "CODE"')
    text = '\n'.join(out) + '\n'
    path = Path(sys.argv[1])
    if not path.exists() or path.read_text() != text:
        path.write_text(text)


if __name__ == '__main__':
    main()
