#!/usr/bin/env python3
"""Write src/physconst.inc from tools/physics.py (one source for the tuning).

    python3 tools/physconst.py src/physconst.inc

The constants and tables go out through dev/tools/verlet/emit.py (written
only when the text changed).
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import physics as P  # noqa: E402
from verlet import emit, tables  # noqa: E402

NAMES = ('GRAVITY', 'VMAX_X', 'VMAX_Y', 'WHEEL_R', 'BOUNCE', 'VT_MAX', 'BRAKE',
         'LEAN_MAX', 'THROTTLE_MAX', 'CONSTRAINT_PASSES', 'RIDER_HIT',
         'SLOPE_MAX', 'LAPS', 'WRAP_MARGIN', 'LEFT_WALL', 'FAR', 'CEILING', 'WHEELBASE',
         'RIDER_UP', 'ROLL_LOSS', 'ENGINE_BRAKE', 'FLIP_DX', 'SPIN_DAMP',
         'GYRO_DIV', 'AIR_SPIN_BRAKE', 'RIDER_HEAVY', 'L2Q_MIN')


def main():
    con = tables(P.LINKS, P.NLEAN)
    consts = [(n, getattr(P, n)) for n in NAMES]
    consts += [('NCONSTRAINTS', len(P.LINKS), 'dec'), ('NLEAN', P.NLEAN, 'dec')]
    air = [-P.AIR_TURN[-lean] if lean < 0 else P.AIR_TURN[lean] for lean in P.LEANS]
    rows = [
        '; constraints: point a, point b; rest length^2 (quarter px) and k8 at',
        '; index constraint * NLEAN + lean + LEAN_MAX (the lean shifts the rider)',
        ('con_a', con['con_a']),
        ('con_b', con['con_b']),
        ('con_l2l', emit.lo(con['con_l2'])),
        ('con_l2h', emit.hi(con['con_l2'])),
        ('con_k8', con['con_k8']),
        '; ground normal for slope index s+SLOPE_MAX, 64 = 1.0',
        ('norm_x', emit.sb(P.NORM_X)),
        ('norm_y', emit.sb(P.NORM_Y)),
        '; air turn per lean level (index lean + LEAN_MAX)',
        ('air_turn', emit.sb(air)),
        "; forward lean level -> the rider's shift, /256 of the wheel axis",
        ('fwd_k', P.FWD_K),
        '; traction per throttle level',
        ('thr_acc', [n * P.THROTTLE_ACC for n in range(P.THROTTLE_MAX + 1)]),
    ]
    emit.emit_inc(sys.argv[1], consts, rows,
                  header=['; physconst.inc -- generated by tools/physconst.py from tools/physics.py.',
                          '; Do not edit: change the model and rebuild.', ''])


if __name__ == '__main__':
    main()
