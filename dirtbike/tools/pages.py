#!/usr/bin/env python3
"""The text pages: HELP and the congratulations after track 30.

    python3 tools/pages.py src/pages.inc build/pages.bin

They go in the TITLE file, after the title tune and before the picture
(tools/music.py, Makefile), so they cost no RAM: show_page (src/title.inc)
reads the file again and prints one. A page is a list of lines, each one
row (scanline), column, text (the game font: upper case), 0; row $FF ends
the page. pages.inc gives PAGES_LEN and each page's offset in pages.bin.
"""
import sys
from pathlib import Path

HELP = [
    (1, 'HOW TO PLAY DIRTBIKE'),
    (3, 'RIDE 3 LAPS AGAINST THE CLOCK. A GAME'),
    (4, 'RUNS THROUGH THE 30 TRACKS IN ORDER; THE'),
    (5, 'MENU OPENS THE FINISHED ONES + THE NEXT.'),
    (7, '          KEYBOARD   JOYSTICK', 1),
    (8, 'GAS       A / UP     BUTTON 0', 1),
    (9, 'HALF GAS  Z / DOWN', 1),
    (10, 'LEAN BACK J / LEFT   LEFT (ANALOG)', 1),
    (11, 'LEAN FWD  L / RIGHT  RIGHT (ANALOG)', 1),
    (12, 'BRAKE     SPACE      BUTTON 1', 1),
    (14, 'R: RESTART    S: SOUND    ESC: MENU'),
    (16, 'POINTS: JUMPS, FLIPS (1000 X FLIPS'),
    (17, 'SQUARED), WHEELIES. THEY COUNT ONCE BACK'),
    (18, 'ON BOTH WHEELS; A CRASH LOSES THEM.'),
    (20, 'LEAN BACK + GAS LIFTS THE FRONT, BRAKE'),
    (21, 'PUTS IT DOWN. IN THE AIR, LEAN TO TURN.'),
    (23, 'PRESS A KEY'),
]

CONGRATS = [
    (3, 'CONGRATULATIONS!'),
    (6, 'YOU HAVE RIDDEN ALL 30 TRACKS'),
    (7, 'OF DIRTBIKE: A REAL CHAMPION!'),
    (10, 'NOW BEAT YOUR RECORDS: EVERY'),
    (11, 'TRACK IS OPEN IN THE MENU.'),
    (16, 'APPLE II PORT: VERHILLE ARNAUD'),
    (22, 'PRESS A KEY'),
]

PAGES = (('page_help', HELP), ('page_congrats', CONGRATS))


def page(lines):
    out = bytearray()
    for row, text, *col in lines:              # (row, text[, column]): centred by default
        assert len(text) <= 40 and text == text.upper(), text
        out += bytes([row * 8, col[0] if col else (40 - len(text)) // 2]) + text.encode() + b'\0'
    return out + b'\xff'


def main():
    data, offs = bytearray(), []
    for name, lines in PAGES:
        offs.append((name, len(data)))
        data += page(lines)
    Path(sys.argv[2]).write_bytes(data)
    Path(sys.argv[1]).write_text(
        '; generated by tools/pages.py -- do not edit\n'
        f'PAGES_LEN = {len(data)}             ; the text pages, in TITLE after the tune\n'
        + ''.join(f'{n.upper()} = {o}\n' for n, o in offs))


if __name__ == '__main__':
    main()
