#!/usr/bin/env python3
"""The tunes: the title page's loop, the finish jingle, the record's tail.

    python3 tools/music.py src/music.inc build/tune.bin

The events are dev/lib/apple2/tune.asm's (encoder: dev/tools/audio/tune.py):
ticks of ~1/60 s, the half period X of sound.asm's tone (0: a rest) and the
flips that fill one tick at that pitch; 0 ends the tune.

The title tune goes at the start of the TITLE file (TUNE_LEN bytes, before
the picture's LZ4FH stream): it costs no RAM, it plays from LOADBUF while
the title is up. The jingles stay in the program (music.inc).
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / 'dev/tools/audio'))
from tune import asm, tune  # noqa: E402,F401  (tune: tests/test_attract.py)

# title: A minor, an eighth = 8 ticks (~225 bpm a quarter)
TITLE = """
A4:1 C5:1 E5:1 A5:1 G5:1 E5:1 C5:1 E5:1  F5:1 A5:1 C6:1 A5:1 G5:2 E5:2
A4:1 C5:1 E5:1 A5:1 G5:1 E5:1 D5:1 C5:1  B4:1 D5:1 G5:1 B5:1 A5:4
E6:2 D6:1 C6:1 B5:2 A5:2  G5:1 A5:1 B5:1 G5:1 E5:4
C6:2 B5:1 A5:1 G5:2 E5:2  D5:1 E5:1 G5:1 B5:1 A5:3 R:1
A5:1 A5:1 C6:1 A5:1 D6:1 A5:1 C6:1 A5:1  G5:1 G5:1 B5:1 G5:1 C6:1 G5:1 B5:1 G5:1
F5:1 A5:1 C6:1 F6:1 E6:1 C6:1 A5:1 C6:1  B5:1 G#5:1 E5:1 G#5:1 A5:4 R:4
"""
# the finish line, then a new record's tail (an eighth = 6 ticks)
JINGLE = "C5:1 E5:1 G5:1 C6:2 G5:1 C6:4"
RECORD = "R:2 E6:1 C6:1 E6:1 G6:1 E6:1 G6:1 C7:6"


def main():
    title = tune(TITLE, 8)
    Path(sys.argv[2]).write_bytes(title)
    Path(sys.argv[1]).write_text(
        '; generated by tools/music.py -- do not edit\n'
        f'TUNE_LEN = {len(title)}               ; the title tune, at the start of TITLE\n'
        '.segment "RODATA"\n' + asm('jingle', tune(JINGLE, 6)) + asm('jingle_rec', tune(RECORD, 6))
        + '.segment "CODE"\n')


if __name__ == '__main__':
    main()
