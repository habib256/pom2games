#!/usr/bin/env python3
"""Pack the 30 tracks into the files the game loads (T01 .. T30), plus the
menu data (names, reference times).

    python3 tools/packtrack.py FHPACK BUILD_DIR

Tnn payload (what the game finds at $9604, after DOS's 4-byte header):
  +0  finish line = lap length, world pixel (16 bits)
  +2  length of stream 2 (16 bits)
  +4  pool length (16 bits)
  +6  length of stream 1 (16 bits)
  +8  stream 2: fhpack (LZ4FH) of 8192 bytes: pattern k[256], rel0[256],
      pool offset lo[256], hi[256], then the pool of partial bytes
      +   stream 1: fhpack of 8192 bytes: heights[4096], pattern ids[4096]
      +   the proven ride (tests/solutions.txt) as runs, for the attract
          demo: count (1..255), then throttle / 4 (bits 5-6), brake (bit 4),
          lean + 4 (bits 0-3); count 0 ends. At most DEMO_MAX bytes.
Both streams unpack to HGR page 2; the game copies them out (render.inc).
build/tracks/menu_data.inc: track names and reference times (tools/solver.py).
"""
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import track  # noqa: E402
import tracks  # noqa: E402
import trackcheck  # noqa: E402
import solver  # noqa: E402

POOL_MAX = 1024                 # the game's pool buffer (render.inc)
DEMOS = (5, 19, 10, 26, 22, 30)  # attract-mode rides (3 laps each), in turn
DEMO_MAX = 400                  # = src/loader.inc's DEMOBUF


def fhpack(tool, data, work):
    raw, packed = work / 'fh.raw', work / 'fh.lz4'
    raw.write_bytes(data)
    subprocess.run([tool, '-c', '-9', '-h', str(raw), str(packed)], check=True, capture_output=True)
    out = packed.read_bytes()
    back = work / 'fh.back'
    subprocess.run([tool, '-d', '-h', str(packed), str(back)], check=True, capture_output=True)
    assert back.read_bytes() == data, 'fhpack round trip'
    return out


def payload(k, tool, work):
    h, fin = tracks.build(k)
    ids, pats, pool, offs = track.compile_patterns(h)
    assert len(pool) <= POOL_MAX, (k, len(pool))
    tab = bytearray(8192)
    for i, (n, rel0, _) in enumerate(pats):
        tab[i], tab[256 + i] = n, rel0
        tab[512 + i], tab[768 + i] = offs[i] & 0xFF, offs[i] >> 8
    tab[1024:1024 + len(pool)] = pool
    s2 = fhpack(tool, bytes(tab), work)
    s1 = fhpack(tool, bytes(h) + bytes(ids), work)
    runs = demo_runs(trackcheck.solutions()[k])
    head = fin.to_bytes(2, 'little') + len(s2).to_bytes(2, 'little') + len(pool).to_bytes(2, 'little') \
        + len(s1).to_bytes(2, 'little')
    return head + s2 + s1 + runs


def demo_runs(inputs):
    runs = []
    for n, (thr, brk, lean) in solver.rle(inputs):
        assert thr in (0, 4, 8) and brk in (0, 1) and -4 <= lean <= 4, (thr, brk, lean)
        while n:
            c = min(n, 255)
            runs += [c, (thr // 4) << 5 | brk << 4 | (lean + 4)]
            n -= c
    runs.append(0)
    assert len(runs) <= DEMO_MAX, len(runs)
    return bytes(runs)


def clock(ticks):
    """Race clock text for a tick count (30 per second), as the game shows it."""
    hun = ticks * 10 // 3
    return f'{hun // 6000}:{hun // 100 % 60:02}.{hun // 10 % 10}'


def main():
    tool, out = sys.argv[1], Path(sys.argv[2])
    out.mkdir(parents=True, exist_ok=True)
    sols = trackcheck.solutions()
    total = 0
    for k in range(1, tracks.NTRACKS + 1):
        data = payload(k, tool, out)
        # the game reads the file at LOADBUF $9600, below its T/S list at
        # $B600 (src/loader.inc): 32 sectors, the DOS header included
        assert len(data) + 4 <= 32 * 256, f'T{k:02}: {len(data)} bytes, more than LOADBUF..TSLBUF'
        (out / f'T{k:02}.bin').write_bytes(data)
        total += len(data)
    lines = ['; menu_data.inc -- generated by tools/packtrack.py. Do not edit.',
             f'.assert NTRACKS = {tracks.NTRACKS}, error, "dirtbike.s: NTRACKS"', 'track_names:']
    lines += [f'        .byte "{n}", 0' for n in tracks.NAMES]
    lines.append('track_par:                      ; reference time, as "M:SS.T"')
    for k in range(1, tracks.NTRACKS + 1):
        lines.append(f'        .byte "{clock(len(sols[k]))}"')
    # attract-mode demos: which tracks, in turn (the rides are in the files)
    lines.append(f'NDEMOS = {len(DEMOS)}')
    lines.append('demo_track: .byte ' + ', '.join(str(k - 1) for k in DEMOS))
    (out / 'menu_data.inc').write_text('\n'.join(lines) + '\n')
    print(f'{tracks.NTRACKS} tracks, {total} bytes')


if __name__ == '__main__':
    main()
