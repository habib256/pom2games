#!/usr/bin/env python3
"""Compile src/textbank.txt into build/textbank.inc (docs/MEMORY.md 13).

The text bank is an image of the auxiliary store (directory entry 28,
segments TBINDEX and TEXTBANK at $0000, so labels are offsets): an index of
2-byte offsets (entry 0 unused; one per text, then one per dictionary word,
then the end), the texts, the dictionary words. memory.s text_fetch copies a
text into tb_buf and expands it: a byte $80 + k (but $A1, a literal of the
original's texts) is dictionary word k, fetched in its place; "@" and the
byte after it (message_region's address) are always literal. The words are
chosen greedily (the longest saving first) among the literal runs of the
texts; a word never contains a token, "@", its operand or the final 0.
"""
import argparse
import collections
import re
from pathlib import Path

TB_MAX = 96          # src/memory.s tb_buf
MAX_IDS = 128        # text_fetch: number * 2 fits a byte
LITERAL = 0xA1       # never a token


def items(data):
    """ca65 .byte items -> list of int (byte) or str (expression)."""
    out, rest = [], data.strip()
    while rest:
        if rest[0] == '"':
            end = rest.index('"', 1)
            out.extend(rest[1:end].encode('ascii'))
            rest = rest[end + 1:]
        else:
            m = re.match(r'([^,]+)', rest)
            token = m.group(1).strip()
            if re.fullmatch(r'\$[0-9A-Fa-f]+', token):
                out.append(int(token[1:], 16))
            elif re.fullmatch(r'\d+', token):
                out.append(int(token))
            else:
                out.append(token)
            rest = rest[m.end():]
        rest = rest.lstrip()
        if rest.startswith(','):
            rest = rest[1:].lstrip()
    return out


def wordable(seq, i):
    x = seq[i]
    return isinstance(x, int) and 0 < x < 0x80 and x != ord('@') and not (
        i and seq[i - 1] == ord('@'))


def dictionary(seqs, limit):
    words = []
    while len(words) < limit:
        count = collections.Counter()
        for s in seqs:
            for n in range(2, 16):
                for i in range(len(s) - n + 1):
                    if all(wordable(s, j) for j in range(i, i + n)):
                        count[tuple(s[i:i + n])] += 1
        best, gain = None, 0
        for seg, c in sorted(count.items()):
            g = c * (len(seg) - 1) - (len(seg) + 2)
            if g > gain:
                best, gain = seg, g
        if not best:
            break
        k = len(words) + (len(words) >= LITERAL - 0x80)       # skip $A1
        words.append(best)
        for s in seqs:
            i = 0
            while i <= len(s) - len(best):
                if tuple(s[i:i + len(best)]) == best and all(wordable(s, j) for j in range(i, i + len(best))):
                    s[i:i + len(best)] = [('tok', 0x80 + k)]
                i += 1
    return words


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('source')
    p.add_argument('out')
    args = p.parse_args()
    texts, aliases = [], []
    for line in Path(args.source).read_text().splitlines():
        line = line.split(';', 1)[0].rstrip() if not line.lstrip().startswith(';') else ''
        if not line.strip():
            continue
        m = re.match(r'^(\w+)\s*=\s*(\w+)$', line)
        if m:
            aliases.append(m.groups())
            continue
        m = re.match(r'^(\w+):\s*(.*)$', line)
        texts.append((m.group(1), items(m.group(2))))
    for name, seq in texts:
        assert seq[-1] == 0 and len(seq) <= TB_MAX, (name, len(seq))
    seqs = [list(seq) for _, seq in texts]
    words = dictionary(seqs, MAX_IDS - 1 - len(texts))
    lines = ['; Generated by tools/gentextbank.py from src/textbank.txt: do not edit.',
             f'; {len(texts)} texts, {sum(len(s) for _, s in texts)} bytes; encoded '
             f'{sum(len(s) for s in seqs)} + dictionary {sum(map(len, words))} '
             f'({len(words)} words).',
             f'TB_DICT = {len(texts) + 1}             ; number of dictionary word 0',
             '.segment "TBINDEX"', '        .word   0']
    lines += [f'        .word   tbt_{n}' for n in range(len(texts))]
    lines += [f'        .word   tbw_{k}' for k in range(len(words))]
    lines += ['        .word   tb_end', '.segment "TEXTBANK"']

    def byte(x):
        if isinstance(x, tuple):
            return f'${x[1]:02X}'
        if isinstance(x, int):
            return f'${x:02X}'
        return x
    for n, ((name, _), seq) in enumerate(zip(texts, seqs)):
        lines.append(f'{name} = {n + 1}')
        lines.append(f'tbt_{n}: .byte ' + ','.join(byte(x) for x in seq))
    for k, w in enumerate(words):
        lines.append(f'tbw_{k}: .byte ' + ','.join(byte(x) for x in w) + f'   ; "{bytes(w).decode()}"')
    lines.append('tb_end:')
    for a, b in aliases:
        lines.append(f'{a} = {b}')
    Path(args.out).write_text('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
