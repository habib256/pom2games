#!/usr/bin/env python3
"""genmenu.py: texts of the start menu of NEOWILD.SYSTEM (lot 7).

Usage: genmenu.py OUT.inc

Writes build/menu.inc for src/boot.s: the 40-column menu screen (six
scenarios of three lines: name, terrain and climate, fauna sentence; the
best score is a placeholder until the hall of fame exists) and the region
names printed under the introduction while the pack loads.

Everything is derived from data already decoded from the original disks:
build/regions/regions.json (names, fauna sentence of GO3, precipitation,
jungle flag) and the map headers (build/map.bin for the Sierra Nevada,
build/maps/rN.bin for the five reconstituted maps: temperatures +13/+14,
base +10, snow level +11). The words are ours (docs/SCENARIOS.md section 3).
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parents[1]
WIDTH = 40
NO_SNOW = 126


def map_path(region, build=HERE / 'build'):
    return build / 'map.bin' if region == 2 else build / f'maps/r{region}.bin'


def climate_line(entry, header):
    """'FOREST, MILD, RAINY, SNOW ABOVE 7200' (feet): terrain, temperature, rain, snow."""
    c = entry['climate']
    if entry['jungle']:
        terrain = 'JUNGLE'
    elif c['precipitation_max'] < 20:
        terrain = 'DESERT'
    else:
        terrain = 'FOREST'
    january, july = (b - 256 if b > 127 else b for b in header[13:15])
    mean = (january + july) / 2
    temperature = 'HOT' if mean >= 75 else 'WARM' if mean >= 60 else 'MILD' if mean >= 45 else 'COLD'
    rain = ('WET' if c['precipitation_max'] >= 100 else
            'RAINY' if c['precipitation_max'] >= 40 else 'DRY')
    base, snow = header[10], header[11]
    snowline = 'NO SNOW' if snow >= NO_SNOW else f'SNOW ABOVE {(base + snow) * 100}'
    return f'{terrain}, {temperature}, {rain}, {snowline}'


def screen(regions, build=HERE / 'build'):
    """The menu as (text, inverse) rows 0..21; rows 22-23 hold the prompts."""
    rows = [(' NEOWILDERNESS - CHOOSE A JOURNEY'.ljust(WIDTH), True), ('', False)]
    for entry in regions:
        r = entry['region']
        header = map_path(r, build).read_bytes()[:64]
        name = f"{r} {entry['name']}{'' if r == 2 else ' *'}"
        best = 'BEST -'
        rows.append((name + ' ' * (WIDTH - 1 - len(name) - len(best)) + best, False))
        rows.append(('  ' + climate_line(entry, header), False))
        rows.append(('  ' + entry['fauna_sentence'], False))
    rows.append(('7 FREE JOURNEY  H HALL OF FAME  Q PRODOS', False))
    rows.append(('* RECONSTITUTED MAP, ORIGINAL REGION', False))
    for text, _ in rows:
        assert len(text) <= WIDTH, text
    return rows


def asm_string(text):
    out, plain = [], ''
    for ch in text:
        if ch in '"':
            raise ValueError(text)
        plain += ch
    if plain:
        out.append(f'"{plain}"')
    return out


def generate(build=HERE / 'build'):
    doc = json.loads((build / 'regions/regions.json').read_text())
    regions = sorted(doc['regions'], key=lambda e: e['region'])
    assert [e['region'] for e in regions] == list(range(1, 7))
    lines = ['; generated by tools/genmenu.py from build/regions/regions.json and the map headers',
             'm_menu:']
    for i, (text, inverse) in enumerate(screen(regions, build)):
        parts = []
        if inverse:
            parts.append('1')
        parts += asm_string(text)
        if inverse:
            parts.append('2')
        # A full 40-column row wraps by itself: no carriage return after it.
        if len(text) < WIDTH:
            parts.append('13')
        lines.append('        .byte   ' + ', '.join(parts))
    lines.append('        .byte   0')
    for entry in regions:
        lines.append(f"m_region{entry['region']}: .byte \"{entry['name']}\", 0")
    lines.append('region_names_lo: .byte ' + ', '.join(f'<m_region{r}' for r in range(1, 7)))
    lines.append('region_names_hi: .byte ' + ', '.join(f'>m_region{r}' for r in range(1, 7)))
    return '\n'.join(lines) + '\n'


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    Path(sys.argv[1]).write_text(generate())


if __name__ == '__main__':
    main()
