#!/usr/bin/env python3
"""genmenu.py: texts of the start menu of NEOWILD.SYSTEM (lot 7).

Usage: genmenu.py OUT.inc

Writes build/menu.inc for src/boot.s: the 40-column menu screen (one line
per scenario in MENU_ORDER, the Sierra Nevada first and chosen by RETURN
alone: key, name, terrain and temperature, best score column; the score is
a placeholder "-" that src/hof_menu.s hm_best overwrites from the hall of
fame), the key -> region and region -> row tables, and the region names
printed under the introduction while the pack loads.

Everything is derived from data already decoded from the original disks:
build/regions/regions.json (names, fauna sentence of GO3, precipitation,
jungle flag) and the map headers (build/map.bin for the Sierra Nevada,
build/maps/rN.bin for the five reconstituted maps: temperatures +13/+14,
base +10, snow level +11). The words are ours (docs/SCENARIOS.md section 3).
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parents[1]
WIDTH = 40
NO_SNOW = 126


def map_path(region, build=HERE / 'build'):
    return build / 'map.bin' if region == 2 else build / f'maps/r{region}.bin'


def climate_tag(entry, header):
    """'FOREST, MILD': terrain and temperature (at most 14 characters)."""
    terrain, temperature, _, _ = climate_line(entry, header).split(', ')
    return f'{terrain}, {temperature}'


def climate_line(entry, header):
    """'FOREST, MILD, RAINY, SNOW ABOVE 7200' (feet): terrain, temperature, rain, snow."""
    c = entry['climate']
    if entry['jungle']:
        terrain = 'JUNGLE'
    elif c['precipitation_max'] < 20:
        terrain = 'DESERT'
    else:
        terrain = 'FOREST'
    january, july = (b - 256 if b > 127 else b for b in header[13:15])
    mean = (january + july) / 2
    temperature = 'HOT' if mean >= 75 else 'WARM' if mean >= 60 else 'MILD' if mean >= 45 else 'COLD'
    rain = ('WET' if c['precipitation_max'] >= 100 else
            'RAINY' if c['precipitation_max'] >= 40 else 'DRY')
    base, snow = header[10], header[11]
    snowline = 'NO SNOW' if snow >= NO_SNOW else f'SNOW ABOVE {(base + snow) * 100}'
    return f'{terrain}, {temperature}, {rain}, {snowline}'


NAME_COL, CLIMATE_COL, BEST_COL = 2, 20, 35      # src/hof_menu.s BEST_COL, hm_best rows 2..7
MENU_ROW = 12                                    # src/boot.s MENU_ROW: the prompts


MENU_ORDER = (2, 1, 3, 4, 5, 6)   # regions by menu key 1..6: the Sierra Nevada first (RETURN)


def screen(regions, build=HERE / 'build', count=6):
    """The menu as (text, inverse) rows 0..10; row MENU_ROW holds the prompts.
    Scenario lines in MENU_ORDER, keyed 1..6 by position; count = 1: the
    Sierra Nevada alone (Neowilderness 140 KB; NeoWildernessXL has the six)."""
    title = ' NEOWILDERNESS XL - CHOOSE A JOURNEY' if count > 1 else ' NEOWILDERNESS - CHOOSE A JOURNEY'
    rows = [(title.ljust(WIDTH), True),
            ('BEST'.rjust(WIDTH), False)]
    by_region = {e['region']: e for e in regions}
    for key, r in enumerate(MENU_ORDER[:count], 1):
        entry = by_region[r]
        header = map_path(r, build).read_bytes()[:64]
        name = entry['name'].ljust(CLIMATE_COL - NAME_COL)
        climate = climate_tag(entry, header).ljust(BEST_COL - CLIMATE_COL)
        rows.append((f'{key} {name}{climate}{"-":>{WIDTH - BEST_COL}}', False))
    rows.append(('T TMAP           GENERATE AN ARCHIPELAGO' if count > 1 else '', False))
    rows.append(('7 FREE JOURNEY    ' + ('ANY REGION, ' if count > 1 else '') + 'NOT RANKED', False))
    # Fidelity lot 1 (src/prepare.s): the original's preparation questions.
    rows.append(('P PREPARATION     QUESTIONS, NOT RANKED', False))
    rows.append(('H HALL OF FAME    Q QUIT TO PRODOS', False))
    for text, _ in rows:
        assert len(text) <= WIDTH, text
    assert len(rows) <= MENU_ROW         # rows 0..11, the prompts on row 12
    return rows


def asm_string(text):
    out, plain = [], ''
    for ch in text:
        if ch in '"':
            raise ValueError(text)
        plain += ch
    if plain:
        out.append(f'"{plain}"')
    return out


def menu_bytes(rows):
    """The .byte lines of one menu text (0-terminated)."""
    lines = []
    for text, inverse in rows:
        parts = []
        if inverse:
            parts.append('1')
        parts += asm_string(text)
        if inverse:
            parts.append('2')
        # A full 40-column row wraps by itself: no carriage return after it.
        if len(text) < WIDTH:
            parts.append('13')
        lines.append('        .byte   ' + ', '.join(parts))
    lines.append('        .byte   0')
    return lines


def generate(build=HERE / 'build'):
    doc = json.loads((build / 'regions/regions.json').read_text())
    regions = sorted(doc['regions'], key=lambda e: e['region'])
    assert [e['region'] for e in regions] == list(range(1, 7))
    lines = ['; generated by tools/genmenu.py from build/regions/regions.json and the map headers']
    # The menu in parts, shared by the editions (src/boot.s menu prints the
    # parts of its list): menu_xl, NeoWildernessXL's six scenarios; menu_1,
    # Neowilderness (140 KB), the Sierra Nevada alone (src/boot.s ld_regions).
    xl, one = screen(regions, build, 6), screen(regions, build, 1)
    assert xl[1:3] == one[1:3] and xl[-2:] == one[-2:] and one[3] == ('', False)
    parts = {'m_title_xl': xl[:1], 'm_title': one[:1], 'm_head': xl[1:3], 'm_more': xl[3:8],
             'm_free_xl': xl[8:10], 'm_free_1': one[3:5], 'm_tail': xl[-2:]}
    for label, rows in parts.items():
        lines.append(label + ':')
        lines += menu_bytes(rows)
    lines.append('menu_xl: .word m_title_xl, m_head, m_more, m_free_xl, m_tail, 0')
    lines.append('menu_1:  .word m_title, m_head, m_free_1, m_tail, 0')
    for entry in regions:
        lines.append(f"m_region{entry['region']}: .byte \"{entry['name']}\", 0")
    lines.append('region_names_lo: .byte ' + ', '.join(f'<m_region{r}' for r in range(1, 7)))
    lines.append('region_names_hi: .byte ' + ', '.join(f'>m_region{r}' for r in range(1, 7)))
    # Menu key (1..6) -> region, and region -> its menu row (hm_best).
    lines.append('menu_regions: .byte ' + ', '.join(str(r) for r in MENU_ORDER))
    lines.append('menu_rows: .byte ' + ', '.join(str(MENU_ORDER.index(r) + 2) for r in range(1, 7)))
    return '\n'.join(lines) + '\n'


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    Path(sys.argv[1]).write_text(generate())


if __name__ == '__main__':
    main()
