#!/usr/bin/env python3
"""genhud.py: colour compass ribbon and survival-panel glyphs (lot 4).

Both use the DHGR small font of dev/lib/hgrc (dhgr_small_font.inc: 4 x 5,
bit 0 = leftmost pixel). Geometry (docs/DHGR.md, "Bandeau et panneaux en
couleur"):

  ribbon  colour columns 56..83 (groups 8..11: bytes 16..23 of each bank),
          rows 0..15, 7 azimuth units per colour pixel: its 28 pixels span
          196 units, like the 98 HGR pixels at 2 units of lot 3. The pointer
          (colour column 70) is ribbon pixel 14.
  strip   cyclic, 80 pixels (560 / 7): N E S W centred on pixels 0, 20, 40,
          60 (rows 2..6), a tick every 35 units (row 9), long every 70 units
          (rows 8..9).
  panels  colour columns 0..55 and 84..139, two text lines each (rows 2..6
          and 9..13), proportional advance = glyph width + 1, space 3.

Usage: genhud.py build/hud.inc            (ribbon strip, pointer, inks)
Library: small_glyph, glyph_columns, strip, pointer_masks (tools/dhgr_ref.py,
tools/gen_summary_font.py).
"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import dhgr_palette as P  # noqa: E402
from gendhgr import POINTER  # noqa: E402

FONT = HERE.parents[1] / 'dev/lib/hgrc/dhgr_small_font.inc'
UNIT = 7                        # azimuth units per ribbon pixel
STRIP = 560 // UNIT             # 80
RIBBON_X0, RIBBON_W = 56, 28    # colour columns 56..83
POINTER_X = 70
TOP_LETTER, TOP_TICK = 2, 8
PANEL_FIELDS = ((2, 1, 56), (9, 1, 56), (2, 85, 140), (9, 85, 140))  # top, x, limit
FIRST, LAST = 32, 90            # panel glyphs (the 7 x 7 font of lot 3: 32..90)
INKS = ('border', 'ink', 'north', 'tick', 'pointer', 'okay', 'soso', 'very', 'alarm')

_font = None


def _load():
    global _font
    if _font is None:
        _font = {}
        for m in re.finditer(r'\.byte ([^;]+); \$([0-9A-Fa-f]{2})', FONT.read_text()):
            _font[int(m.group(2), 16)] = tuple(int(v.strip()[1:], 16) for v in m.group(1).split(','))
    return _font


def small_glyph(ch):
    """Five rows (bit 0 = leftmost pixel) of a character; outside 32..90: space."""
    code = ord(ch) if isinstance(ch, str) else ch
    if not FIRST <= code <= LAST:
        code = FIRST
    return _load()[code][:5]


def glyph_columns(ch):
    """Column masks (bit r = row r) up to the last lit column; a blank glyph
    is two empty columns (advance 3)."""
    rows = small_glyph(ch)
    cols = [sum(1 << r for r in range(5) if rows[r] >> c & 1) for c in range(4)]
    while cols and not cols[-1]:
        cols.pop()
    return cols or [0, 0]


def strip():
    """80 bytes: bits 0..4 letter column (rows 2..6), bit 5 row 8, bit 6 row 9,
    bit 7 north ink."""
    out = [0] * STRIP
    for s in range(0, STRIP, 5):
        out[s] |= 0x40 | (0x20 if s % 10 == 0 else 0)
    for i, letter in enumerate('NESW'):
        cols = glyph_columns(letter)
        left = 20 * i - len(cols) // 2
        for k, mask in enumerate(cols):
            out[(left + k) % STRIP] |= mask | (0x80 if letter == 'N' else 0)
    return out


def pointer_masks():
    """Columns 68..72 of the pointer: bit k = row 11 + k."""
    top = POINTER[0][0]
    return [sum(1 << (row - top) for row, half in POINTER if abs(x - POINTER_X) <= half)
            for x in range(POINTER_X - 2, POINTER_X + 3)]


def table(name, data):
    return [f'{name}:'] + ['        .byte   ' + ', '.join(f'${v:02X}' for v in data[k:k + 16])
                           for k in range(0, len(data), 16)]


def main():
    rows = ['; generated by tools/genhud.py from dev/lib/hgrc/dhgr_small_font.inc']
    rows += [f'HUD_{name.upper()} = {P.HUD[name]}' for name in INKS]
    rows += table('hud_strip', strip()) + table('hud_ptr_mask', pointer_masks())
    Path(sys.argv[1]).write_text('\n'.join(rows) + '\n')


if __name__ == '__main__':
    main()
