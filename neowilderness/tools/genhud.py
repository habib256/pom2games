#!/usr/bin/env python3
"""genhud.py: the cyclic compass ribbon of the DHGR band (lot 4).

140 strip columns, one per DHGR colour pixel, 4 azimuth units each (560 per
turn, magnetic north at column 0). Byte bits 0..6: letter rows 1..7 of the
ribbon (tools/dhgr_font.py glyphs, labels centred on their bearing);
bit 7: tick (rows 9..10), every 1/16 turn. src/hud.s draws 42 of them
around the pointer; tools/dhgr_ref.hud_banks is the reference.
"""
from pathlib import Path
import sys
sys.path.insert(0, str(Path(__file__).resolve().parent))
from dhgr_font import glyph, width

COLUMNS = 140
LABELS = ('N', 'NE', 'E', 'SE', 'S', 'SW', 'W', 'NW')


def strip():
    cols = bytearray(COLUMNS)
    for bearing, label in enumerate(LABELS):
        centre = (bearing * 35 + 1) // 2          # 17.5 columns apart, rounded up
        x = centre - width(label) // 2
        for letter in label:
            w, rows = glyph(letter)
            for r, bits in enumerate(rows):
                for b in range(w):
                    if bits >> b & 1:
                        cols[(x + b) % COLUMNS] |= 1 << r
            x += w + 1
    for tick in range(16):
        cols[(tick * 35 + 2) // 4] |= 0x80          # round(tick * 8.75)
    return bytes(cols)


def main():
    data = strip()
    lines = ['; Generated by tools/genhud.py: 4 azimuth units per strip column.',
             '.segment "LOWCODE"', 'hud_strip:']
    for i in range(0, COLUMNS, 14):
        lines.append('        .byte ' + ','.join(f'${b:02X}' for b in data[i:i + 14]))
    Path(sys.argv[1]).write_text('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
