#!/usr/bin/env python3
"""genstars.py: tables of the star module src/stars.s (wildsky.bin, lot 7).

Output (ca65 include, e.g. build/stars/stars_tables.inc), every value from
tools/stars_ref.py / tools/stars_catalog.py:
  STAR_COUNT            catalogue size (282)
  STAR_LIST_MAX_REF     list size (src/stars_draw.s STAR_LIST_MAX must agree)
  STAR_K1, STAR_K2      first index (16 bits) of selection class 1 and 2
                        after the priority stars; st_prio_cls: their classes
  STAR_SOLID0..3        solid DHGR entry c << 4 | c of looks 0..3 (white,
                        yellow, light blue, grey), for src/stars_draw.s
  st_cat, st_cat2       the catalogue, 3 bytes per star (tools/stars_catalog.py):
                        its first STAR_CAT_HEAD stars in segment STARS_CATALOGUE
                        (a store record of its own, 462 bytes: it fills the
                        464-byte hole of the auxiliary language card), the
                        others in STARS_CATALOGUE2 (head of the module image),
                        contiguous at run time:
                        RAq bits 7-0; south << 7 | first magnitude << 6 |
                        look << 4 | RAq bits 11-8; |dec|
  st_c_lo/_hi           C(8 i) = alpha_sun(day 8 i, 0 h UT) - 32768, 47 words
  st_t9                 T[k] & 255, T[k] = ceil(512 k / sqrt(k^2 + 2304)), k = 1..80;
                        STAR_T_HIGH: first index whose T is >= 256
  st_atbits             AT[r] = round(atan(r / 128) * 560 / 2 pi), r = 0..128, as
                        its 128 steps of 0 or 1 (bit r - 1, least significant
                        first): the module rebuilds AT in its BSS
The small tables are split by field (structure of arrays) so that the 6502
indexes them with X; the catalogue (more than 256 records) is read through a
zero-page pointer. Usage: genstars.py OUT.inc [--names OUT_NAMES.inc]
"""
import argparse, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import stars_ref as R  # noqa: E402
import stars_catalog as K  # noqa: E402


CAT_HEAD = 154                  # 462 bytes: src/wild.cfg SKYCAT


def table(name, data, width=16, fmt='${:02X}'):
    rows = [f'{name}:']
    for k in range(0, len(data), width):
        rows.append('        .byte   ' + ', '.join(fmt.format(v) for v in data[k:k + width]))
    return rows


def tables():
    cat = R.CATALOGUE
    prio, (k1, k2) = R.LAYOUT
    rows = ['; generated by tools/genstars.py from tools/stars_ref.py and tools/stars_catalog.py',
            f'STAR_COUNT = {len(cat)}', f'STAR_LIST_MAX_REF = {R.LIST_MAX}',
            f'STAR_BUCKETS_REF = {R.BUCKETS}', f'STAR_H_MAX = {R.H_MAX}',
            f'STAR_PRIO = {len(prio)}', f'STAR_K1 = {k1}', f'STAR_K2 = {k2}']
    rows += [f'STAR_SOLID{t} = ${c << 4 | c:02X}' for t, c in enumerate(R.COLOURS)]
    rows += [f'STAR_ROWS{t} = {r}' for t, r in enumerate(R.ROWS)]
    rows += table('st_prio_cls', [c << 6 for c in prio])
    head = min(CAT_HEAD, len(cat))
    rows.append(f'STAR_CAT_HEAD = {head}')
    rows += ['.pushseg', '.segment STARS_CATALOGUE']
    rows += table('st_cat', [b for s in cat[:head] for b in s['record']], width=15)
    rows += ['.segment STARS_CATALOGUE2']
    rows += table('st_cat2', [b for s in cat[head:] for b in s['record']], width=15)
    rows += ['.popseg']
    rows += table('st_c_lo', [c & 255 for c in R.C_TABLE])
    rows += table('st_c_hi', [c >> 8 for c in R.C_TABLE])
    def nibbles(gaps):
        gaps = list(gaps) + [0] * (len(gaps) & 1)
        assert max(gaps) < 16
        return [gaps[i] | gaps[i + 1] << 4 for i in range(0, len(gaps), 2)]
    rows.append(f'STAR_T_GAPS = {len(R.T_GAPS)}')
    rows += table('st_tgap', nibbles(R.T_GAPS))
    rows.append(f'STAR_TU_BASE = {R.TU_BASE}')
    rows.append(f'STAR_TU_GAPS = {len(R.TU_GAPS)}')
    rows += ['.pushseg', '.segment STARS_TUGAP']     # the game: resident (GCODE)
    rows += table('st_tugap', nibbles(R.TU_GAPS))
    rows += ['.popseg']
    steps = [b - a for a, b in zip(R.AT_TABLE, R.AT_TABLE[1:])]
    assert set(steps) <= {0, 1} and len(steps) == 128
    rows += table('st_atbits', [sum(steps[8 * i + j] << j for j in range(8)) for i in range(16)])
    return rows


def names():
    """LOOK STARS: high-ASCII names of the first-magnitude stars (catalogue
    index order) and of the two landmarks, each terminated by 0."""
    rows = ['; generated by tools/genstars.py: LOOK STARS names (docs/STARS.md)']
    first = [s['name'] for s in R.CATALOGUE if s['big']]
    rows.append(f'STAR_NAMED = {len(first)}')
    for k, n in enumerate(first + [K.LANDMARK_NAMES[1], K.LANDMARK_NAMES[2]]):
        rows.append(f'st_name{k}: .byte ' + ', '.join(f'${ord(c) | 0x80:02X}' for c in n) + ', 0')
    return rows


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('out', type=Path)
    ap.add_argument('--names', type=Path)
    a = ap.parse_args()
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text('\n'.join(tables()) + '\n')
    if a.names:
        a.names.write_text('\n'.join(names()) + '\n')


if __name__ == '__main__':
    main()
