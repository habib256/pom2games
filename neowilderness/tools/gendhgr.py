#!/usr/bin/env python3
"""gendhgr.py: resident DHGR tables of the game (lot 3), from tools/dhgr_palette.

Output (ca65 include, build/dhgr_tables.inc):
  dhgr_moods    10 moods x 21 entries: the five sky zones (zenith, zenith/mid
                dither, mid, mid/glow dither, glow), then the 16 entries after
                the sky of dhgr_palette.mood_table (docs/DHGR.md 3.2): ground 3,
                snow 3, water 3, ridge, outline, trunk, crown odd, crown even,
                sun ($FF none), shade index ($FF: sprites hidden). An entry is
                a << 4 | b, a where (row + azimuth) is even.
  dhgr_shades   the distinct sprite shade tables, 16 bytes each.
  dhgr_assets   day colours of the 4 original sprite codes, overlays 5..9.
  constants     MOOD_SIZE, MOOD_COUNT, tier and sky-zone limits.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import dhgr_palette as P  # noqa: E402

ASSETS = ('wreck', 'bear', 'cougar', 'rattlesnake', 'cabin')   # overlays 5..9
POINTER = ((11, 2), (12, 1), (13, 0))   # compass index (tools/genhud.py): (row, half width) around column 70


def table(name, data, width=16):
    rows = [f'{name}:']
    for k in range(0, len(data), width):
        rows.append('        .byte   ' + ', '.join(f'${v:02X}' for v in data[k:k + width]))
    return rows


def zones(sky):
    """The five sky zone entries from the zenith, mid and glow entries: a
    dither zone takes colour a of the upper entry, b of the lower one."""
    z, m, g = sky
    return [z, z & 0xF0 | m & 0x0F, m, m & 0xF0 | g & 0x0F, g]


def resident_moods():
    table = P.mood_table()
    out = []
    for k in range(len(P.MOODS)):
        entry = table[19 * k:19 * k + 19]
        out += zones(entry[:3]) + list(entry[3:])
    return out, table[19 * len(P.MOODS):]


def main():
    moods, shades = resident_moods()
    size = 21
    count = len(P.MOODS)
    rows = ['; generated by tools/gendhgr.py from tools/dhgr_palette.py',
            f'MOOD_SIZE = {size}', f'MOOD_COUNT = {count}',
            # ray step n of wild.s is the step number + 127
            f'TIER1_N = {127 + P.NEAR + 1}', f'TIER2_N = {127 + P.MID + 1}',
            f'SUN_DAY = {P.SUN_DAY}', f'SUN_GOLDEN = {P.SUN_GOLDEN}',
            f'SUN_HORIZON = {P.SUN_HORIZON}', f'SUN_CIVIL = {P.SUN_CIVIL}',
            f'MOON_LOW = {P.MOON_LOW}', f'LIGHT_BRIGHT = {P.LIGHT_BRIGHT}',
            f'LIGHT_DIM = {P.LIGHT_DIM}',
            f'MOON_HIGH_COLOUR = ${P.MOON_HIGH * 17:02X}',
            f'MOON_LOW_COLOUR = ${P.MOON_LOW_COLOUR * 17:02X}']
    for i, m in enumerate(P.MOODS):
        rows.append(f'MOOD_{m.upper().replace(" ", "_")} = {i}')
    rows += [f'SKY_ROW{k} = {v}' for k, v in enumerate(P.SKY_ROWS)]
    rows += table('dhgr_moods', moods, size)
    rows += table('dhgr_shades', shades)
    rows += table('dhgr_assets', [c for a in ASSETS for c in P.SPRITES[a]], 4)
    Path(sys.argv[1]).write_text('\n'.join(rows) + '\n')


if __name__ == '__main__':
    main()
