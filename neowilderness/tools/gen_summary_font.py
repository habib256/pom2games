#!/usr/bin/env python3
"""Survival-panel glyphs (WILDHUD): characters 32..90 of the DHGR small font,
four column masks each (bit r = row r of 5, trailing columns zero), the form
drawn by hud_col (src/hud.s). Width = last non-zero column + 1."""
from pathlib import Path
import sys
sys.path.insert(0, str(Path(__file__).resolve().parent))
from genhud import FIRST, LAST, glyph_columns, small_glyph  # noqa: E402

out = ['; generated by tools/gen_summary_font.py from dev/lib/hgrc/dhgr_small_font.inc',
       'summary_font:']
for code in range(FIRST, LAST + 1):
    cols = glyph_columns(chr(code)) if any(small_glyph(code)) else []
    cols = (cols + [0, 0, 0, 0])[:4]
    out.append('        .byte   ' + ', '.join(f'${c:02X}' for c in cols) + f'  ; {chr(code)!r}')
Path(sys.argv[1]).write_text('\n'.join(out) + '\n')
