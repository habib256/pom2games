#!/usr/bin/env python3
"""src/room.h from the missions of tools/model.py (one source for both)."""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from model import MISSIONS, OBJECTS, ROOM_COLS, room_objects, room_start, room_tiles

out = Path(__file__).resolve().parents[1] / 'src/room.h'
lines = ['/* Generated by tools/gen_room.py from tools/model.py: do not edit. */',
         f'#define MISSIONS {len(MISSIONS)}u',
         'static const char *const mission_names[] = {'
         + ', '.join(f'"{name}"' for name, _, _ in MISSIONS) + '};',
         'static const unsigned char mission_goals[] = {'
         + ', '.join(str(goal) for _, goal, _ in MISSIONS) + '};',
         '/* Tiles, 4 bits each, 2 per byte, the first in the low bits. */',
         'static const unsigned char mission_tiles[][180] = {']
for name, _, room in MISSIONS:
    tiles = room_tiles(room)
    packed = [tiles[i] | tiles[i + 1] << 4 for i in range(0, len(tiles), 2)]
    lines.append('    { /* ' + name + ' */')
    for r in range(0, len(packed), 15):
        lines.append('        ' + ', '.join(f'0x{b:02X}' for b in packed[r:r + 15]) + ',')
    lines.append('    },')
lines.append('};')
# Per mission: drone A x, y, drone B x, y (255 255: none), technician x, y,
# objects count, then kind, x, y.
lines.append(f'static const unsigned char mission_starts[][{7 + 3 * OBJECTS}] = {{')
for name, _, room in MISSIONS:
    objs = room_objects(room)
    b = room_start('E', room) if any('E' in r for r in room) else (255, 255)
    row = list(room_start('D', room)) + list(b) + list(room_start('T', room)) + [len(objs)]
    for o in objs:
        row += o
    row += [0] * (7 + 3 * OBJECTS - len(row))
    lines.append('    {' + ', '.join(str(v) for v in row) + '},')
lines.append('};')
text = '\n'.join(lines) + '\n'
if not out.exists() or out.read_text() != text:
    out.write_text(text)
