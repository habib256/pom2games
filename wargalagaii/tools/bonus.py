#!/usr/bin/env python3
"""WARGALAGA II tables from tools/model.py -> src/bonus.inc: object kinds
and drop_table (lot 5), level kinds and per-level parameters at loop 0
(lot 6; setup_level applies the loops), the shop's items (lot 7), Meteor
Storm's and Memory Station's constants (lot 8), the pickup texts. The 6502 and the model share
them.

    tools/bonus.py            write src/bonus.inc (if changed)
    tools/bonus.py --check    fail if src/bonus.inc is stale
"""
from pathlib import Path
import sys

import model

OUT = Path(__file__).resolve().parents[1] / 'src/bonus.inc'
ITEM_NAME = 12                  # shop names, padded
PICK_LEN = 12                   # render.s MSG_LEN


def emit():
    out = ['; Generated by tools/bonus.py -- do not edit.', f'NKIND = {len(model.KINDS)}']
    out += [f'K_{name.upper()} = {i}' for i, name in enumerate(model.KINDS)]
    out.append('drop_table:')
    for i in range(0, 64, 16):
        out.append('        .byte ' + ','.join(str(k) for k in model.DROP_TABLE[i:i + 16]))
    out.append('; levels: kind (0 normal, 1 big, 2 bonus, 3 kamikaze, 4 boss), then the')
    out.append('; loop-0 parameters: dive gap, max divers, fire gap, bomb dy, kamikaze dy')
    tables = [('lv_combo', [model.alien_combo(lv) for lv in range(model.LEVELS)]),
              ('lv_big', [model.big_combo(lv) for lv in range(model.LEVELS)])]
    for name, values in tables:
        out.append(f'{name}:')
        for i in range(0, len(values), 20):
            out.append('        .byte ' + ','.join(str(v) for v in values[i:i + 20]))
    # Lot 10: the rest of a level's record lives in aux memory (game.cfg
    # AUXLV, WG2.AUX at $9C00); setup_level copies the level's LV_REC bytes.
    # Lot 10b: then its formation (model.level_form): rows, the 5 rows'
    # masks, the staggered rows and the second species' rows (bits).
    fields = ('kind', 'dive', 'divers', 'fire', 'bomb', 'kami', 'rows', 'mask', 'stagger', 'design')
    offset = 0
    for name in fields:
        out.append(f'LV_{name.upper()} = {offset}')
        offset += model.ROWS if name == 'mask' else 1
    out.append(f'LV_REC = {offset}')
    out += ['.pushseg', '.segment "LEVELS"', 'lv_recs:']
    for lv in range(model.LEVELS):
        rows, masks, stagger, design = model.level_form(lv)
        rec = [model.level_kind(lv)] + list(model.level_params(lv, 0)) + [rows, *masks, stagger, design]
        assert len(rec) == offset
        out.append('        .byte ' + ','.join(map(str, rec)) + f'   ; level {lv + 1}')
    out.append('.popseg')
    # the shop (lot 7): prices in BCD, names for the shop screen
    out.append(f'NITEM = {len(model.ITEMS)}')
    out.append(f'SHOP_MIN = ${model.SHOP_MIN:04}')
    out.append(f'AUTO_T = {model.duration(model.T_MAX)}')
    out.append(f'RANK_MAX = {model.RANK_MAX}')
    out.append('item_lo: .byte ' + ','.join(f'${p % 100:02}' for _, p in model.ITEMS))
    out.append('item_hi: .byte ' + ','.join(f'${p // 100:02}' for _, p in model.ITEMS))
    out.append(f'ITEM_NAME = {ITEM_NAME}')
    out += ['.pushseg', '.segment "SHOP"            ; the shop overlay only', 'item_name:']
    for name, _ in model.ITEMS:
        out.append(f'        .byte "{name.ljust(ITEM_NAME)}"')
    out.append('.popseg')
    # the sub-games (lot 8)
    M = model
    for name in ('ROCK', 'M_ROCKS', 'M_SMALL0', 'M_SPEED_MAX', 'M_ACC', 'M_DEC', 'M_WARM', 'M_DY0',
                 'M_SPACING', 'M_DIST', 'M_WAIT', 'M_END', 'M_TOP', 'M_PICK', 'M_BIG', 'M_MEDIUM', 'M_XMAX',
                 'M_SHIP_MAX', 'M_TIME_MAX', 'MEM_NONE'):
        out.append(f'{name} = {getattr(M, name)}')
    out.append(f'M_CRASH_PTS_BCD = ${M.M_CRASH_PTS:04}')
    # lot 11: the storm's objects and prizes, resident with its code
    tiers = [M.M_MEGA, *M.M_TIERS]
    assert all(t[2] % 10000 == 0 for t in tiers)
    out += ['.pushseg', '.segment "STORM2"']
    out.append('m_picks:  .byte ' + ','.join(f'K_{k.upper()}' for k in M.M_PICKS))
    out.append('m_tier_pct: .byte ' + ','.join(str(t[1]) for t in M.M_TIERS))
    out.append('m_tier_top: .byte ' + ','.join(f'${M.bcd(t[2], 3)[2]:02X}' for t in tiers))
    out.append('m_tier_hi:  .byte ' + ','.join(f'${M.bcd(t[2], 3)[1]:02X}' for t in tiers))
    out.append('m_tier_clo: .byte ' + ','.join(f'${M.bcd(t[3], 2)[0]:02X}' for t in tiers))
    out.append('m_tier_chi: .byte ' + ','.join(f'${M.bcd(t[3], 2)[1]:02X}' for t in tiers))
    out.append('.popseg')
    assert M.MEM_CELLS == max(c * r for c, r in M.MEM_GRIDS)   # (game.s: MEM_CELLS)
    out.append(f'.assert MEM_CELLS = {M.MEM_CELLS}, error, "MEM_CELLS: tools/model.py"')
    out.append(f'MEM_ROUNDS = {len(M.MEM_GRIDS)}')
    out.append(f'MEM_PRIZE = ${M.MEM_PRIZE:06}')
    out.append('mem_cols: .byte ' + ','.join(str(c) for c, r in M.MEM_GRIDS))
    out.append('mem_rows: .byte ' + ','.join(str(r) for c, r in M.MEM_GRIDS))
    out.append('mem_kinds: .byte ' + ','.join(f'K_{k.upper()}' for k in M.MEM_KINDS))
    # what a pickup did (render.s msg_draw), in aux memory (lot 11): texts padded centred
    out.append(f'PICK_T = {M.PICK_T}')
    out += [f'{n} = {getattr(M, n)}' for n in ('PM_POINTS', 'PM_LESS_SPEED', 'PM_LESS_BULLET', 'PM_LOST',
                                                 'PM_MEGA')]
    out.append(f'NPICK = {len(M.PICK_TEXT)}')
    out.append('.pushseg')
    out.append('.segment "PICK"')
    out.append('PICK_AUX:      ; (aux memory: render.s fetches a text, pick_fetch)')
    for k, text in enumerate(M.PICK_TEXT):
        out.append(f'pick_{k}: .byte "{text.center(PICK_LEN)}"')
    out.append('.popseg')
    return '\n'.join(out) + '\n'


def main():
    text = emit()
    if '--check' in sys.argv:
        if OUT.read_text() != text:
            sys.exit(f'{OUT} is stale: run tools/bonus.py')
        return
    if not OUT.exists() or OUT.read_text() != text:
        OUT.write_text(text)


if __name__ == '__main__':
    main()
