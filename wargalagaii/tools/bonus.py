#!/usr/bin/env python3
"""WARGALAGA II tables from tools/model.py -> src/bonus.inc: object kinds
and drop_table (lot 5), level kinds and per-level parameters at loop 0
(lot 6; setup_level applies the loops). The 6502 and the model share them.

    tools/bonus.py            write src/bonus.inc (if changed)
    tools/bonus.py --check    fail if src/bonus.inc is stale
"""
from pathlib import Path
import sys

import model

OUT = Path(__file__).resolve().parents[1] / 'src/bonus.inc'


def emit():
    out = ['; Generated by tools/bonus.py -- do not edit.', f'NKIND = {len(model.KINDS)}']
    out += [f'K_{name.upper()} = {i}' for i, name in enumerate(model.KINDS)]
    out.append('drop_table:')
    for i in range(0, 64, 16):
        out.append('        .byte ' + ','.join(str(k) for k in model.DROP_TABLE[i:i + 16]))
    out.append('; levels: kind (0 normal, 1 big, 2 bonus, 3 kamikaze, 4 boss), then the')
    out.append('; loop-0 parameters: dive gap, max divers, fire gap, bomb dy, kamikaze dy')
    tables = [('lv_kind', [model.level_kind(lv) for lv in range(model.LEVELS)]),
              ('lv_combo', [model.alien_combo(lv) for lv in range(model.LEVELS)]),
              ('lv_big', [model.big_combo(lv) for lv in range(model.LEVELS)])]
    for k, name in enumerate(('lv_dive', 'lv_divers', 'lv_fire', 'lv_bomb', 'lv_kami')):
        tables.append((name, [model.level_params(lv, 0)[k] for lv in range(model.LEVELS)]))
    for name, values in tables:
        out.append(f'{name}:')
        for i in range(0, len(values), 20):
            out.append('        .byte ' + ','.join(str(v) for v in values[i:i + 20]))
    return '\n'.join(out) + '\n'


def main():
    text = emit()
    if '--check' in sys.argv:
        if OUT.read_text() != text:
            sys.exit(f'{OUT} is stale: run tools/bonus.py')
        return
    if not OUT.exists() or OUT.read_text() != text:
        OUT.write_text(text)


if __name__ == '__main__':
    main()
