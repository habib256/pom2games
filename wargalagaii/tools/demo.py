#!/usr/bin/env python3
"""WARGALAGA II attract mode (lot 9): the autopilot's inputs -> src/demo.inc.

The demo starts at level 1 and SEED, then visits levels 3, 4, 8 and 25
through model.DEMO_NEXT (the normal game keeps its sequential levels):
src/demo.s feeds logic_step one input per step from this script, as the
autopilot (tools/autopilot.py) chose them on tools/model.py. It always
fires (pressed and held), so a step is just a move: the script is runs of
one byte, move code << 6 | steps (1..63), move codes 0 none, 1 right,
2 left; a 0 byte ends it. The shop and Memory Station close at once in
the demo (noshop), as the autopilot leaves them.

    tools/demo.py            write src/demo.inc (if changed)
    tools/demo.py --check    fail if src/demo.inc is stale
"""
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
import autopilot
import model as M

OUT = Path(__file__).resolve().parents[1] / 'src/demo.inc'
DEMO_STEPS = 3000                    # ordinary, big, kamikaze, bonus, then boss
CODES = {0: 0, 1: 1, -1: 2}


def moves():
    game = M.Game(0)
    out = []
    for _ in range(DEMO_STEPS):
        move = autopilot.choose(game) if game.alive() and not game.phase else 0
        play(game, move)
        out.append(move)
    return out


def play(game, move):
    """One demo step on the model, as the 6502 does it."""
    game.demo = True
    game.step(move, True, True)
    if game.station:
        game.station_exit()
    if game.shop:
        game.shop_exit()


def encode(script):
    out, k = [], 0
    while k < len(script):
        n = 1
        while k + n < len(script) and script[k + n] == script[k] and n < 63:
            n += 1
        out.append(CODES[script[k]] << 6 | n)
        k += n
    return bytes(out + [0])


def decode(data):
    back = {v: k for k, v in CODES.items()}
    out = []
    for b in data[:data.index(0)]:
        out += [back[b >> 6]] * (b & 63)
    return out


def emit():
    data = encode(moves())
    lines = ['; Generated by tools/demo.py: the attract mode\'s moves (src/demo.s).',
             f'DEMO_STEPS = {DEMO_STEPS}', f'DEMO_JUMPS = {len(M.DEMO_NEXT)}',
             'demo_from: .byte ' + ','.join(map(str, M.DEMO_NEXT)),
             'demo_to: .byte ' + ','.join(map(str, M.DEMO_NEXT.values())),
             'demo_script:']
    for k in range(0, len(data), 16):
        lines.append('        .byte ' + ','.join(f'${b:02X}' for b in data[k:k + 16]))
    return '\n'.join(lines) + '\n'


def main():
    text = emit()
    if '--check' in sys.argv:
        if OUT.read_text() != text:
            sys.exit(f'{OUT} is stale: run tools/demo.py')
        return
    if not OUT.exists() or OUT.read_text() != text:
        OUT.write_text(text)
    else:
        OUT.touch()                    # acknowledge unchanged dependencies


if __name__ == '__main__':
    main()
