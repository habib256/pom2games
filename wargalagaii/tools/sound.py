#!/usr/bin/env python3
"""WARGALAGA II sound data -> src/sound.inc.

Sound effects, one step per frame (30 Hz NTSC), for both back-ends:
  Mockingboard: second AY chip, voice A, with or without noise;
  speaker: a half-period counted in turns of timing.s's wait loop, played
  only in the time a frame waits for its flip (never delaying it).
Music (Mockingboard only, first AY chip): MELODY and BASS below, (note,
sixteenths), None = rest; tools/pt3.py makes the PT3 module of them.
Original tune (A minor), not taken from Warblade.

    tools/sound.py            write src/sound.inc (if changed)
    tools/sound.py --check    fail if src/sound.inc is stale
"""
from pathlib import Path
import random
import sys

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'src/sound.inc'
AY_CLOCK = 1_023_000            # Mockingboard AY: the Apple II clock
CPU = 1_020_484
MUS_HZ = 25                     # PT3 ticks a second (timer 1; tools/pt3.py's
                                # SPEED follows): half the usual 50, half the
                                # cost (~1 600 cycles a tick, lot 6 measures)
SPK_TURN = 63                   # cycles of one wait-loop turn (timing.s; the
                                # test checks it: bug hunts 5 and 6)

NAMES = ['C', 'C#', 'D', 'D#', 'E', 'F', 'F#', 'G', 'G#', 'A', 'A#', 'B']


def midi(name):
    pitch, octave = name[:-1], int(name[-1])
    return 12 * (octave + 1) + NAMES.index(pitch)


def hz(m):
    return 440 * 2 ** ((m - 69) / 12)


def ay_period(f):
    return max(1, min(4095, round(AY_CLOCK / (16 * f))))


def spk_turns(f):
    """Speaker half-period in wait-loop turns (1..255), 0 = silent."""
    return 0 if not f else max(1, min(255, round(CPU / (2 * f * SPK_TURN))))


# Sound effects: (frequency Hz or 0, noise 0/1, AY volume 0-15) per frame.
# Events from logic.s, highest priority first (bit 0 = most important).
rng = random.Random(1983)
SFX = [
    ('death', [(rng.randint(90, 400), 1, max(0, 15 - k // 2)) for k in range(26)]),
    ('over', [(hz(midi(n)), 0, 13) for n in ('E4', 'E4', 'E4', 'C4', 'C4', 'C4', 'A3', 'A3', 'A3', 'A3',
                                             'A3', 'A3')] + [(0, 0, 0)]),
    ('armour', [(400 + 150 * k, 0, 13) for k in range(7)]),
    ('kill', [(rng.randint(250, 1100), 1, 14 - 2 * k) for k in range(7)]),
    ('shot', [(2200 - 250 * k, 0, 11 - k) for k in range(6)]),
]

MELODY = [('A4', 2), ('E5', 2), ('A5', 2), ('E5', 2), ('G5', 2), ('E5', 2), ('D5', 2), ('E5', 2),
          ('C5', 2), ('E5', 2), ('A5', 2), ('E5', 2), ('B4', 2), ('D5', 2), ('G5', 2), ('D5', 2),
          ('A4', 2), ('E5', 2), ('A5', 2), ('E5', 2), ('G5', 2), ('E5', 2), ('D5', 2), ('C5', 2),
          ('B4', 2), ('C5', 2), ('D5', 2), ('E5', 2), ('E5', 4), (None, 4)]
BASS = [('A2', 4), ('A2', 4), ('E2', 4), ('E2', 4), ('F2', 4), ('F2', 4), ('G2', 4), ('G2', 4),
        ('A2', 4), ('A2', 4), ('E2', 4), ('E2', 4), ('F2', 4), ('G2', 4), ('E2', 4), ('E2', 4)]


def emit():
    out = ['; Generated by tools/sound.py -- do not edit.', f'SPK_TURN = {SPK_TURN}', f'MUS_HZ = {MUS_HZ}',
           f'NSFX = {len(SFX)}']
    for k, (name, _) in enumerate(SFX):
        out.append(f'EV_{name.upper()} = {1 << k}')
    out.append('sfx_lo: .lobytes ' + ','.join(f'sfx_{n}' for n, _ in SFX))
    out.append('sfx_hi: .hibytes ' + ','.join(f'sfx_{n}' for n, _ in SFX))
    out.append('; a step: AY period lo, hi, mixer (chip 2: $3E tone, $37 noise), volume,')
    out.append('; speaker turns (0 silent); a volume of $FF ends the effect')
    for name, steps in SFX:
        out.append(f'sfx_{name}:')
        for f, noise, vol in steps:
            p = ay_period(f) if f else 0
            mixer = 0x37 if noise else 0x3E
            out.append(f'        .byte ${p & 255:02X},${p >> 8:02X},${mixer:02X},{vol},{spk_turns(f)}')
        out.append('        .byte 0,0,$3E,$FF,0')
    return '\n'.join(out) + '\n'


def main():
    text = emit()
    if '--check' in sys.argv:
        if OUT.read_text() != text:
            sys.exit(f'{OUT} is stale: run tools/sound.py')
        return
    if not OUT.exists() or OUT.read_text() != text:
        OUT.write_text(text)


if __name__ == '__main__':
    main()
