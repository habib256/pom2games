#!/usr/bin/env python3
"""WARGALAGA II flight paths -> src/paths.inc.

Curves are drawn with a turtle in screen dots (x right, y down, heading in
degrees, 0 = right, 90 = down), sampled once per logic step and quantised
with the error carried over, so the sum of the steps lands where the curve
does. One step is one byte: high nibble dx in CELLS (two dots), low nibble
dy in rows, both signed 4-bit (-7..7). $80 ends a path. No trigonometry at
run time; a path flown on the right half is mirrored (dx negated).

Entry paths start at an absolute place (cell x, row y; rows 192-255 stand
for -64..-1, above the screen). Dive paths are relative: they start where
the alien sits in the formation, rising a little before they turn down.

    tools/paths.py            write src/paths.inc (if changed)
    tools/paths.py --check    fail if src/paths.inc is stale
"""
import math
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'src/paths.inc'
END = 0x80


def fly(start, heading, segments):
    """Segments: (steps, speed, turn degrees over the segment). -> dots."""
    x, y = start
    out = []
    for steps, speed, turn in segments:
        for _ in range(steps):
            heading += turn / steps
            x += speed * math.cos(math.radians(heading))
            y += speed * math.sin(math.radians(heading))
            out.append((x, y))
    return out


def quantise(start, points):
    """Dots -> step bytes; start is in dots too."""
    qx, qy = round(start[0] / 2), round(start[1])
    steps = []
    for x, y in points:
        nx, ny = round(x / 2), round(y)
        dx, dy = nx - qx, ny - qy
        assert -7 <= dx <= 7 and -7 <= dy <= 7, (dx, dy)
        steps.append((dx & 15) << 4 | (dy & 15))
        qx, qy = nx, ny
    assert END not in steps
    return steps


# Entry: from above the left third, down and to the right, one loop in the
# middle of the screen, then up towards the formation (homing finishes).
ENTRY_START = (40, -20)
ENTRY = fly(ENTRY_START, 75, [(26, 4, 0), (36, 4, -330), (10, 4, 0)])

# Authored WGII entry scripts: a readable arc, a wide sweep, the original
# loop, and an S bend. Same start; all end above the ship before homing.
# These are original curves inspired by Warblade's scripted squadrons.
ENTRIES = [
    [(40 + 100 * t, -20 + 95 * t + 18 * math.sin(math.pi * t))
     for t in (k / 56 for k in range(1, 57))],
    fly(ENTRY_START, 30, [(22, 3, 0), (28, 3, 150), (12, 3, 0)]),
    ENTRY,
    [(40 + 100 * t + 20 * math.sin(2 * math.pi * t),
      -20 + 95 * t + 40 * math.sin(math.pi * t))
     for t in (k / 64 for k in range(1, 65))],
]
STAGE_ROUTES = (0, 1, 2, 0, 1, 3, 2, 3)


def entries():
    return [quantise(ENTRY_START, points) + [END] for points in ENTRIES]


def entry_index(level, wave):
    return (STAGE_ROUTES[level % 8] + wave) % 4

# Bonus levels (lot 6): the same way in, then out through the bottom (the
# alien never seats: it escapes when it leaves the screen).
FLYPAST = fly(ENTRY_START, 75, [(26, 4, 0), (36, 4, -330), (44, 4, 0)])

DIVE_START = (0, 0)
DIVES = [
    # loop dive: turn outwards and down, drift back to the middle
    fly(DIVE_START, -90, [(12, 3, -180), (20, 4, -20), (40, 4, 0)]),
    # zigzag
    fly(DIVE_START, -90, [(10, 3, -180), (4, 4, 25)] + [(8, 4, -50 * (-1) ** k) for k in range(8)]),
    # diagonal, then back across
    fly(DIVE_START, -90, [(10, 3, -180), (8, 4, -30), (24, 4, 0), (10, 4, 70), (30, 4, 0)]),
    # loop in the lower half
    fly(DIVE_START, -90, [(10, 3, -180), (16, 4, 0), (30, 4, -360), (30, 4, 0)]),
]


def data():
    entry = quantise(ENTRY_START, ENTRY) + [END]
    dives = [quantise(DIVE_START, d) + [END] for d in DIVES]
    start = (round(ENTRY_START[0] / 2), round(ENTRY_START[1]) & 0xFF)
    return start, entry, dives


def flypast():
    return quantise(ENTRY_START, FLYPAST) + [END]


def decode(byte):
    dx, dy = byte >> 4, byte & 15
    return dx - 16 if dx > 7 else dx, dy - 16 if dy > 7 else dy


def emit():
    start, entry, dives = data()
    out = ['; Generated by tools/paths.py -- do not edit.',
           f'ENTRY_X0 = {start[0]}',
           f'ENTRY_Y0 = {start[1]}',
           f'NDIVES = {len(dives)}',
           'entry_lo: .lobytes ' + ','.join(f'entry{k}' for k in range(4)),
           'entry_hi: .hibytes ' + ','.join(f'entry{k}' for k in range(4)),
           'stage_routes: .byte ' + ','.join(map(str, STAGE_ROUTES)),
           '.pushseg', '.segment "FLIGHT"',
           'dive_lo: .lobytes ' + ','.join(f'dive{k}' for k in range(len(dives))),
           'dive_hi: .hibytes ' + ','.join(f'dive{k}' for k in range(len(dives)))]
    for k, steps in enumerate(dives):
        if k == len(dives) - 1:
            out.append('.popseg')    # last dive in main: room for the long demo
        name = f'dive{k}'
        out.append(f'{name}:')
        for i in range(0, len(steps), 16):
            out.append('        .byte ' + ','.join(f'${b:02X}' for b in steps[i:i + 16]))
    for name, steps in [('flypast', flypast())] + [(f'entry{k}', d) for k, d in enumerate(entries())]:
        if name == 'entry2':
            out.append('entry:')    # legacy default pointer for cleared state
        out.append(f'{name}:')
        for i in range(0, len(steps), 16):
            out.append('        .byte ' + ','.join(f'${b:02X}' for b in steps[i:i + 16]))
    return '\n'.join(out) + '\n'


def main():
    _, entry, dives = data()
    for points in ENTRIES:
        assert all(0 <= x <= 266 and -20 <= y < 160 for x, y in points)
        assert len(points) < 256
    for d in dives:                        # a dive must leave the screen
        assert sum(decode(b)[1] for b in d[:-1]) >= 192 - 20, 'dive too short'
        rise = min(0, min(sum(decode(b)[1] for b in d[:k]) for k in range(len(d))))
        assert rise > -16, 'a dive may not climb above the HUD into rows 192+'
    text = emit()
    if '--check' in sys.argv:
        if OUT.read_text() != text:
            sys.exit(f'{OUT} is stale: run tools/paths.py')
        return
    if not OUT.exists() or OUT.read_text() != text:
        OUT.write_text(text)


if __name__ == '__main__':
    main()
